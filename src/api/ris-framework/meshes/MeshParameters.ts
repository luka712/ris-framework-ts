/**
 * Parameters for a mesh.
 */
export class MeshParameters {

    /**
     * The positions.
     */
    public positions: number[] = [];

    /**
     * The indices.
     */
    public indices?: number[];

    /**
     * The uv texture coordinates.
     */
    public textureCoords?: number[];

    /**
     * The colors of a mesh.
     */
    public colors?: number[];
}
